const MARKDOWN_HEADER: &str = "# MCP Console recording transcript\n\n<!-- Generated by MCP Console. Do not edit. -->\n\nResults record response assembly; transport write evidence is retained separately in capture/events.jsonl.\n\n";
pub(super) struct Writers {
    markdown: ProjectionWriter,
    directory: PathBuf,
    documents: Documents,
}
struct ProjectionWriter {
    writer: BufWriter<File>,
    header_written: bool,
    description: &'static str,
}
/// Source-only state, shared by live QMD projection and capture reconstruction.
#[derive(Default)]
pub(super) struct Documents {
    calls: BTreeMap<u64, CallToolRequestParams>,
    pub(super) sessions: BTreeMap<u64, QuartoWriter>,
    metadata: Metadata,
    current: Option<u64>,
}
#[derive(Clone, Default)]
struct Metadata {
    working_directory: String,
    requirements: Value,
    r_requirements: Vec<String>,
    python_requirements: Vec<String>,
    dynamic_resolution: bool,
    r_available: bool,
    metadata_known: bool,
}
#[derive(Clone)]
pub(super) struct QuartoWriter {
    metadata: Metadata,
    sources: Vec<QuartoSource>,
    environment_boundaries: bool,
}
#[derive(Clone)]
struct QuartoSource {
    language: &'static str,
    contents: String,
}
impl Writers {
    pub(super) fn new(
        directory: &Path,
        working_directory: &Path,
        dynamic_resolution: bool,
        r_available: bool,
        requirements: &crate::worker_client::Declaration,
        metadata_known: bool,
    ) -> Result<Self, String> {
        let markdown = super::create_private_file(&directory.join("transcript.md"))
            .map_err(|e| e.to_string())?;
        Ok(Self {
            markdown: ProjectionWriter::new(markdown, "Markdown transcript"),
            directory: directory.to_owned(),
            documents: Documents {
                metadata: Metadata {
                    working_directory: working_directory
                        .to_str()
                        .ok_or("Quarto execution root requires a UTF-8 working directory")?
                        .into(),
                    requirements: serde_json::to_value(requirements).map_err(|e| e.to_string())?,
                    r_requirements: requirements.r.clone(),
                    python_requirements: requirements.python.clone(),
                    dynamic_resolution,
                    r_available,
                    metadata_known,
                },
                ..Default::default()
            },
        })
    }
    pub(super) fn relocate(&mut self, directory: &Path) -> Result<(), String> {
        self.markdown.writer = BufWriter::new(
            std::fs::OpenOptions::new()
                .append(true)
                .open(directory.join("transcript.md"))
                .map_err(|e| e.to_string())?,
        );
        self.directory = directory.to_owned();
        Ok(())
    }
    pub(super) fn append(&mut self, event: &Envelope<'_>) -> Result<(), String> {
        let mut fragment = String::new();
        render_event(&mut fragment, event)?;
        let value = serde_json::to_value(event).map_err(|e| e.to_string())?;
        let changed = self.documents.observe(&value)?;
        for id in changed {
            let document = &self.documents.sessions[&id];
            if document.has_source() {
                let path = self.directory.join(format!("sessions/session-{id:03}.qmd"));
                let first = !path.exists();
                super::replace_private_file(&path, document.render().as_bytes())?;
                if first {
                    writeln!(
                        fragment,
                        "[Session {id:03} source](<sessions/session-{id:03}.qmd>)\n"
                    )
                    .unwrap();
                }
            }
        }
        self.markdown.append(MARKDOWN_HEADER, &fragment)?;
        if let Event::WorkerEnded { session_id, .. } = &event.event {
            let path = self
                .directory
                .join(format!("sessions/session-{session_id:03}.qmd"));
            if path.exists() {
                super::make_read_only(&path)?;
            }
        }
        Ok(())
    }
    pub(super) fn finalize(&mut self) -> Result<(), String> {
        self.markdown.writer.flush().map_err(|e| e.to_string())?;
        super::make_read_only(&self.directory.join("transcript.md"))?;
        for id in self.documents.sessions.keys() {
            let path = self.directory.join(format!("sessions/session-{id:03}.qmd"));
            if path.exists() {
                super::make_read_only(&path)?;
            }
        }
        Ok(())
    }
}
impl Documents {
    pub(super) fn observe(&mut self, event: &Value) -> Result<Vec<u64>, String> {
        let mut changed = Vec::new();
        match event["event"].as_str().unwrap_or("") {
            "recording_started" => {
                self.metadata.working_directory =
                    event["working_directory"].as_str().unwrap_or("").into();
                self.metadata.metadata_known = !event["dynamic_resolution"].is_null();
                self.metadata.dynamic_resolution =
                    event["dynamic_resolution"].as_bool().unwrap_or(false);
                if let Some(req) = event.get("startup_requirements").filter(|v| !v.is_null()) {
                    self.metadata.requirements(req);
                }
            }
            "environment_discovered" => {
                self.metadata.metadata_known = true;
                self.metadata.dynamic_resolution =
                    event["dynamic_resolution"].as_bool().unwrap_or(false);
                self.metadata.r_available = event["r_available"].as_bool().unwrap_or(false);
                self.metadata.requirements(&event["startup_requirements"]);
                if let Some(id) = self.current {
                    self.sessions.get_mut(&id).unwrap().metadata = self.metadata.clone();
                    changed.push(id);
                }
            }
            "worker_started" => {
                self.metadata.requirements(&event["requirements"]);
                let id = event["session_id"]
                    .as_u64()
                    .ok_or("worker session missing")?;
                self.current = Some(id);
                self.sessions.insert(
                    id,
                    QuartoWriter {
                        metadata: self.metadata.clone(),
                        sources: Vec::new(),
                        environment_boundaries: false,
                    },
                );
            }
            "worker_ended" => self.current = None,
            "tool_call" => {
                let id = event["call_id"].as_u64().ok_or("call ID missing")?;
                self.calls.insert(
                    id,
                    serde_json::from_value(event["request"].clone()).map_err(|e| e.to_string())?,
                );
            }
            "source_associated" => {
                let call_id = event["call_id"].as_u64().ok_or("call ID missing")?;
                let id = event["session_id"]
                    .as_u64()
                    .ok_or("worker session missing")?;
                let request = self
                    .calls
                    .get(&call_id)
                    .ok_or("associated source has no request")?;
                let document = self
                    .sessions
                    .get_mut(&id)
                    .ok_or("associated source has no session")?;
                let before = (
                    document.sources.len(),
                    document.metadata.r_requirements.len(),
                    document.metadata.python_requirements.len(),
                );
                if document.metadata.dynamic_resolution
                    && let Some(requirements) = declared_requirements(request)
                {
                    extend_unique(&mut document.metadata.r_requirements, requirements.r);
                    extend_unique(
                        &mut document.metadata.python_requirements,
                        requirements.python,
                    );
                }
                // Retain every submitted string, including invalid multi-language calls.
                for language in ["r", "python", "sql"] {
                    if let Some(source) = request
                        .arguments
                        .as_ref()
                        .and_then(|a| a.get(language))
                        .and_then(Value::as_str)
                    {
                        document.sources.push(QuartoSource {
                            language,
                            contents: source.into(),
                        });
                    }
                }
                if before
                    != (
                        document.sources.len(),
                        document.metadata.r_requirements.len(),
                        document.metadata.python_requirements.len(),
                    )
                {
                    changed.push(id);
                }
            }
            "python_environment_accepted" => {
                self.metadata.python_requirements = strings(&event["packages"]);
                if let Some(id) = self.current {
                    self.sessions
                        .get_mut(&id)
                        .unwrap()
                        .metadata
                        .python_requirements = self.metadata.python_requirements.clone();
                    changed.push(id);
                }
            }
            "requirements_selected" => {
                self.metadata
                    .requirements(&event["snapshot"]["requirements"]);
                if let Some(id) = self.current {
                    let document = self.sessions.get_mut(&id).unwrap();
                    document.environment_boundaries = true;
                    document.sources.push(QuartoSource {
                        language: "",
                        contents: format!(
                            "Requirements selected ({}):\n\n```json\n{}\n```\n\n",
                            event["action"].as_str().unwrap_or(""),
                            serde_json::to_string_pretty(&event["snapshot"])
                                .map_err(|e| e.to_string())?
                        ),
                    });
                    changed.push(id);
                }
            }
            _ => {}
        }
        Ok(changed)
    }
}
fn strings(value: &Value) -> Vec<String> {
    value
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(Value::as_str)
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default()
}
impl Metadata {
    fn requirements(&mut self, value: &Value) {
        if !value.is_null() {
            self.requirements = value.clone();
            self.r_requirements = strings(&value["r"]);
            self.python_requirements = strings(&value["python"]);
        }
    }
}
impl QuartoWriter {
    fn has_source(&self) -> bool {
        self.sources.iter().any(|s| !s.language.is_empty())
    }
    pub(super) fn render(&self) -> String {
        let mut document = String::from(
            "---\n# Source recorded by MCP Console; review before executing.\ntitle: MCP Console session\n",
        );
        if !self.metadata.metadata_known || self.environment_boundaries {
            document.push_str("execute:\n  eval: false\n");
        }
        if !self.metadata.metadata_known {
            document.push_str("mcp-console:\n  environment: unknown\n");
        } else {
            document.push_str("ir:\n  isolated: true\n");
            push_yaml_sequence(&mut document, "  packages", &self.metadata.r_requirements);
            push_yaml_sequence(
                &mut document,
                "  python-packages",
                &self.metadata.python_requirements,
            );
            document.push_str("mcp-console:\n  original-working-directory: ");
            document.push_str(&yaml_string(&self.metadata.working_directory));
            document.push('\n');
            writeln!(
                document,
                "  r-available: {}\n  dynamic-resolution: {}",
                self.metadata.r_available, self.metadata.dynamic_resolution
            )
            .unwrap();
            push_yaml_sequence(
                &mut document,
                "  duckdb-extensions",
                &strings(&self.metadata.requirements["duckdb"]),
            );
            push_yaml_sequence(
                &mut document,
                "  python-version",
                &strings(&self.metadata.requirements["python_version"]),
            );
            if let Some(value) = self.metadata.requirements["exclude_newer"].as_str() {
                writeln!(document, "  exclude-newer: {}", yaml_string(value)).unwrap();
            }
        }
        document.push_str("---\n\nThis source includes failed or rejected submissions.\nIt is not a checkpoint or a guarantee of independent reproducibility.\n\n");
        if self.environment_boundaries {
            document.push_str("Recreate the environments at the recorded boundaries before enabling execution.\nCells may require incompatible declarations; the header is not a replay manifest.\n\n");
        }
        for source in &self.sources {
            if source.language.is_empty() {
                document.push_str(&source.contents);
            } else {
                push_quarto_fence(
                    &mut document,
                    &format!("{{{}}}", source.language),
                    source.language,
                    &source.contents,
                );
            }
        }
        document
    }
}
struct DeclaredRequirements<'a> {
    r: Vec<&'a str>,
    python: Vec<&'a str>,
}

fn declared_requirements(request: &CallToolRequestParams) -> Option<DeclaredRequirements<'_>> {
    if request.name != "send" {
        return None;
    }
    let requirements = request
        .arguments
        .as_ref()?
        .get("requirements")?
        .as_object()?;
    if matches!(
        requirements.get("action").and_then(Value::as_str),
        Some("get" | "set" | "reset")
    ) {
        return None;
    }
    let r = requirement_strings(requirements, "r")?;
    let python = requirement_strings(requirements, "python")?;
    if r.is_empty() && python.is_empty() {
        return None;
    }
    Some(DeclaredRequirements { r, python })
}

fn requirement_strings<'a>(
    requirements: &'a Map<String, Value>,
    language: &str,
) -> Option<Vec<&'a str>> {
    match requirements.get(language) {
        Some(values) => values.as_array()?.iter().map(Value::as_str).collect(),
        None => Some(Vec::new()),
    }
}

fn extend_unique<'a>(requirements: &mut Vec<String>, additions: impl IntoIterator<Item = &'a str>) {
    for requirement in additions {
        if !requirements.iter().any(|existing| existing == requirement) {
            requirements.push(requirement.to_string());
        }
    }
}

fn push_yaml_sequence(document: &mut String, name: &str, values: &[String]) {
    if values.is_empty() {
        writeln!(document, "{name}: []").expect("writing to a String cannot fail");
        return;
    }
    writeln!(document, "{name}:").expect("writing to a String cannot fail");
    for value in values {
        let value = yaml_string(value);
        writeln!(document, "    - {value}").expect("writing to a String cannot fail");
    }
}

fn yaml_string(value: &str) -> String {
    if is_plain_yaml_string(value) {
        value.to_string()
    } else {
        let json = serde_json::to_string(value).expect("serializing a string cannot fail");
        let mut yaml = String::with_capacity(json.len());
        for character in json.chars() {
            match character {
                '\u{0085}' => yaml.push_str("\\N"),
                '\u{2028}' => yaml.push_str("\\L"),
                '\u{2029}' => yaml.push_str("\\P"),
                '\u{007f}'..='\u{009f}' => {
                    write!(yaml, "\\x{:02X}", character as u32)
                        .expect("writing to a String cannot fail");
                }
                '\u{feff}' | '\u{fffe}' | '\u{ffff}' => {
                    write!(yaml, "\\u{:04X}", character as u32)
                        .expect("writing to a String cannot fail");
                }
                _ => yaml.push(character),
            }
        }
        yaml
    }
}

fn is_plain_yaml_string(value: &str) -> bool {
    let Some(first) = value.chars().next() else {
        return false;
    };
    if !matches!(first, 'A'..='Z' | 'a'..='z' | '_' | '/')
        || value.chars().any(char::is_control)
        || value.chars().any(|character| {
            matches!(
                character,
                '\u{0085}' | '\u{2028}' | '\u{2029}' | '\u{feff}' | '\u{fffe}' | '\u{ffff}'
            )
        })
        || value.trim() != value
        || value.ends_with(':')
        || value
            .chars()
            .zip(value.chars().skip(1))
            .any(|(previous, character)| previous.is_whitespace() && character == '#')
        || value
            .split(':')
            .skip(1)
            .any(|suffix| suffix.starts_with(char::is_whitespace))
    {
        return false;
    }
    !matches!(
        value.to_ascii_lowercase().as_str(),
        "null" | "true" | "false"
    )
}

impl ProjectionWriter {
    fn new(file: File, description: &'static str) -> Self {
        Self {
            writer: BufWriter::new(file),
            header_written: false,
            description,
        }
    }

    fn append(&mut self, header: &str, fragment: &str) -> Result<(), String> {
        if !self.header_written {
            self.writer
                .write_all(header.as_bytes())
                .map_err(|error| format!("failed to append {}: {error}", self.description))?;
        }
        self.writer
            .write_all(fragment.as_bytes())
            .and_then(|()| self.writer.flush())
            .map_err(|error| format!("failed to append {}: {error}", self.description))?;
        self.header_written = true;
        Ok(())
    }
}

fn render_event(document: &mut String, envelope: &Envelope<'_>) -> Result<(), String> {
    match &envelope.event {
        Event::Protocol { .. }
        | Event::Delivery { .. }
        | Event::RecordingActivated
        | Event::OutputText { .. }
        | Event::SourceAssociated { .. }
        | Event::CellStarted { .. }
        | Event::CellEnded { .. }
        | Event::SourceAttached { .. }
        | Event::WorkerReady { .. }
        | Event::ImageOmitted { .. } => Ok(()),
        Event::RecordingEnded => {
            document.push_str("## Recording finished\n\n");
            Ok(())
        }
        Event::ProcessOutput { .. } => Ok(()),
        Event::WorkerStarted {
            session_id, pid, ..
        } => {
            writeln!(
                document,
                "## Session {session_id:03} started\n\nWorker process {pid}.\n"
            )
            .unwrap();
            Ok(())
        }
        Event::WorkerEnded {
            session_id,
            outcome,
        } => {
            writeln!(document, "## Session {session_id:03} ended\n").unwrap();
            push_fence(document, "text", outcome);
            Ok(())
        }
        Event::EnvironmentDiscovered {
            dynamic_resolution,
            python_preparation,
            r_available,
            startup_requirements,
        } => {
            document.push_str("## Runtime discovery\n\n");
            push_json(
                document,
                &json!({ "dynamic_resolution": dynamic_resolution, "python_preparation": python_preparation, "r_available": r_available, "startup_requirements": startup_requirements }),
            )
        }
        Event::PythonEnvironmentAccepted { packages } => {
            document.push_str("## Accepted Python environment\n\n");
            push_json(document, &json!({ "packages": packages }))
        }
        Event::RecordingStarted {
            working_directory, ..
        } => {
            let metadata = json!({
                "run_id": envelope.run_id,
                "started_at": envelope.at,
                "working_directory": working_directory,
            });
            document.push_str("## Console process\n\n");
            push_json(document, &metadata)
        }
        Event::RequirementsSelected {
            call_id,
            action,
            snapshot,
        } => {
            document.push_str("## Requirements selected\n\n");
            push_json(
                document,
                &json!({"call_id": call_id, "action": action, "snapshot": snapshot}),
            )
        }
        Event::ToolCall {
            call_id, request, ..
        } => render_tool_call(document, *call_id, request),
        Event::ArtifactCreated {
            artifact_id,
            call_id,
            path,
            ..
        } => {
            let owner = call_id.map_or_else(|| "session".into(), |id| format!("call {id}"));
            writeln!(
                document,
                "## Artifact {artifact_id} for {owner}

[Artifact {artifact_id} from {owner}](<{path}>)
"
            )
            .expect("writing to a String cannot fail");
            Ok(())
        }
        Event::SessionOutput {
            path,
            retained_bytes,
            discarded_bytes,
            ..
        } => {
            if *retained_bytes != 0 || *discarded_bytes != 0 {
                writeln!(document, "## Session output\n\n[Startup and idle output](<{path}>)\n\n{retained_bytes} raw bytes retained; {discarded_bytes} raw bytes not retained in this file.\n")
                    .expect("writing to a String cannot fail");
            }
            Ok(())
        }
        Event::StartupFailed { message, .. } => {
            document.push_str("## Startup failed\n\n");
            push_fence(document, "text", message);
            Ok(())
        }
        Event::CellOutput {
            call_id,
            path,
            retained_bytes,
            inline_omitted_bytes,
            discarded_bytes,
            ..
        } => {
            {
                writeln!(
                    document,
                    "## Retained output for call {call_id}

[Retained text output for call {call_id}](<{path}>)

{retained_bytes} raw bytes retained; {inline_omitted_bytes} rendered UTF-8 bytes omitted from inline responses; {discarded_bytes} raw bytes not retained in this file.
"
                )
                .expect("writing to a String cannot fail");
            }
            Ok(())
        }
        Event::ToolResult {
            call_id, outcome, ..
        } => render_tool_result(document, *call_id, outcome),
    }
}

fn render_tool_call(
    document: &mut String,
    call_id: u64,
    request: &CallToolRequestParams,
) -> Result<(), String> {
    let Some(send) = parse_send(request) else {
        writeln!(document, "## Call {call_id}: Tool request\n")
            .expect("writing to a String cannot fail");
        if let Some(source) = submitted_source(request) {
            push_fence(document, source.language, source.contents);
            document.push_str("### Raw request\n\n");
        }
        return push_json(document, request);
    };

    let label = send.label();
    writeln!(document, "## Call {call_id}: {label}\n").expect("writing to a String cannot fail");
    if let Some(source) = send.source {
        push_fence(document, source.language, source.contents);
    }
    if let Some(stdin) = send.stdin {
        document.push_str("### Submitted stdin\n\n");
        push_fence(document, "text", stdin);
    }
    if !send.options.is_empty() {
        document.push_str("### Options\n\n");
        push_json(document, &Value::Object(send.options))?;
    }
    Ok(())
}

struct Send<'a> {
    source: Option<Source<'a>>,
    stdin: Option<&'a str>,
    options: Map<String, Value>,
}

impl Send<'_> {
    fn label(&self) -> &'static str {
        if let Some(source) = self.source {
            return source.label;
        }
        match self.options.get("control").and_then(Value::as_str) {
            Some("interrupt") => return "Interrupt",
            Some("restart") => return "Restart",
            _ => {}
        }
        if self.stdin.is_some() {
            return "Stdin";
        }
        if self.options.contains_key("requirements") {
            return "Requirements";
        }
        if self.options.is_empty() || self.options.keys().all(|key| key == "timeout_ms") {
            "Poll"
        } else {
            "Send"
        }
    }
}

#[derive(Clone, Copy)]
struct Source<'a> {
    label: &'static str,
    language: &'static str,
    contents: &'a str,
}

fn submitted_source(request: &CallToolRequestParams) -> Option<Source<'_>> {
    if request.name != "send" {
        return None;
    }
    let arguments = request.arguments.as_ref()?;
    let mut source = None;
    for (field, label, language) in [
        ("r", "R", "r"),
        ("python", "Python", "python"),
        ("sql", "SQL", "sql"),
    ] {
        let Some(value) = arguments.get(field) else {
            continue;
        };
        let value = value.as_str()?;
        if source
            .replace(Source {
                label,
                language,
                contents: value,
            })
            .is_some()
        {
            return None;
        }
    }
    source
}

fn parse_send(request: &CallToolRequestParams) -> Option<Send<'_>> {
    if request.name != "send"
        || request.input_responses.is_some()
        || request.request_state.is_some()
    {
        return None;
    }
    let arguments = match request.arguments.as_ref() {
        Some(arguments) => arguments,
        None => {
            return Some(Send {
                source: None,
                stdin: None,
                options: Map::new(),
            });
        }
    };
    if arguments.keys().any(|key| {
        !matches!(
            key.as_str(),
            "r" | "python" | "sql" | "stdin" | "control" | "requirements" | "timeout_ms"
        )
    }) {
        return None;
    }
    let source = submitted_source(request);
    if source.is_none()
        && arguments
            .keys()
            .any(|key| matches!(key.as_str(), "r" | "python" | "sql"))
    {
        return None;
    }
    let stdin = match arguments.get("stdin") {
        Some(stdin) => Some(stdin.as_str()?),
        None => None,
    };
    let options = arguments
        .iter()
        .filter(|(key, _)| !matches!(key.as_str(), "r" | "python" | "sql" | "stdin"))
        .map(|(key, value)| (key.clone(), value.clone()))
        .collect();
    Some(Send {
        source,
        stdin,
        options,
    })
}

fn render_tool_result(
    document: &mut String,
    call_id: u64,
    outcome: &Outcome<'_>,
) -> Result<(), String> {
    writeln!(document, "## Result for call {call_id}\n").expect("writing to a String cannot fail");
    match outcome {
        Outcome::Result { result } => render_result(document, call_id, result),
        Outcome::Error { error } => {
            document.push_str("### Tool error\n\n");
            push_json(document, error)
        }
    }
}

fn render_result(
    document: &mut String,
    call_id: u64,
    result: &RecordedResult<'_>,
) -> Result<(), String> {
    if result.is_error == Some(true) {
        document.push_str("### Tool result error\n\n");
    }
    if result.content.is_empty() {
        document.push_str("_No content._\n\n");
    }
    for block in &result.content {
        match block {
            RecordedContent::Text(text) => push_fence(document, "text", &text.text),
            RecordedContent::Image {
                artifact_id, path, ..
            } => {
                writeln!(document, "![Artifact {artifact_id}](<{path}>)\n")
                    .expect("writing to a String cannot fail");
            }
            RecordedContent::Other(content) => {
                let kind = match content {
                    ContentBlock::Text(_) => "text",
                    ContentBlock::Image(_) => "image",
                    ContentBlock::Audio(_) => "audio",
                    ContentBlock::Resource(_) => "resource",
                    ContentBlock::ResourceLink(_) => "resource_link",
                    _ => "unknown",
                };
                return Err(format!(
                    "Markdown transcript has unsupported content kind {kind:?} for call {call_id}"
                ));
            }
        }
    }
    Ok(())
}

fn push_json(document: &mut String, value: &(impl Serialize + ?Sized)) -> Result<(), String> {
    let json = serde_json::to_string_pretty(value)
        .map_err(|error| format!("failed to render Markdown transcript JSON: {error}"))?;
    push_fence(document, "json", &json);
    Ok(())
}

pub(super) fn push_fence(document: &mut String, language: &str, contents: &str) {
    push_fence_with_prefix(document, language, "", contents);
}

fn push_quarto_fence(document: &mut String, language: &str, source_language: &str, contents: &str) {
    let prefix = if starts_with_quarto_cell_option(source_language, contents) {
        "\n"
    } else {
        ""
    };
    push_fence_with_prefix(document, language, prefix, contents);
}

fn starts_with_quarto_cell_option(language: &str, contents: &str) -> bool {
    let comment = match language {
        "r" | "python" => "#",
        "sql" => "--",
        _ => return false,
    };
    let first_line = contents.split_once('\n').map_or(contents, |(line, _)| line);
    first_line
        .trim_start()
        .strip_prefix(comment)
        .map(str::trim_start)
        .is_some_and(|line| line.starts_with('|'))
}

fn push_fence_with_prefix(document: &mut String, language: &str, prefix: &str, contents: &str) {
    let longest = contents
        .split(|character| character != '`')
        .map(str::len)
        .max()
        .unwrap_or_default();
    let fence = "`".repeat((longest + 1).max(3));
    writeln!(document, "{fence}{language}").expect("writing to a String cannot fail");
    document.push_str(prefix);
    document.push_str(contents);
    if !contents.ends_with('\n') {
        document.push('\n');
    }
    writeln!(document, "{fence}\n").expect("writing to a String cannot fail");
}
